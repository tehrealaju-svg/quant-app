// Inlines ui/index.html's stylesheets, scripts and images into one page and writes it as a C++
// header (the exe shows it with set_html, so there are no files or local server to manage).
//   node tools/bundle.mjs <ui dir> <out.h>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [dir, out] = process.argv.slice(2);
const read = (f) => readFileSync(join(dir, f), "utf8");
let html = read("index.html");
html = html.replace(/<link rel="stylesheet" href="([^"]+\.css)">/g, (_, f) => `<style>\n${read(f)}\n</style>`);
html = html.replace(/<script src="([^"]+\.js)"><\/script>/g, (_, f) => `<script>\n${read(f).replace(/<\/script>/g, "<\\/script>")}\n</script>`);
html = html.replace(/(src|href)="([^"]+\.svg)"/g, (_, attr, f) => `${attr}="data:image/svg+xml;base64,${Buffer.from(read(f)).toString("base64")}"`);
html = html.replace(/url\('([^']+\.svg)'\)/g, (_, f) => `url('data:image/svg+xml;base64,${Buffer.from(read(f)).toString("base64")}')`);

// Split into chunks: some compilers limit the length of one string literal.
const chunks = [];
for (let i = 0; i < html.length; i += 12000) chunks.push(html.slice(i, i + 12000));
const body = chunks.map((c) => `R"QUANTUI(${c})QUANTUI"`).join("\n");
writeFileSync(out, `// Generated by tools/bundle.mjs from ui/. Do not edit.\n#pragma once\nstatic const char* QUANT_UI_HTML =\n${body};\n`);
console.log(`bundled ${html.length} bytes`);
